#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	char	*result;

	result = NULL;
	while (*s != '\0')
	{
		if (*s == (const char)c)
			result = (char *)s;
		s++;
	}
	if (!c)
		return ((char *)s);
	return (result);
}
